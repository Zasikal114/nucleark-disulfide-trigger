#!/bin/bash
# FoldX disulfide bond analysis pipeline — structured output
set -e

FOLDX="${FOLDX_BIN:-/app/foldx}"
PROJ="${WORKDIR:-/app}"
INPUT="$PROJ/Input"
RESULTS="$PROJ/results"

if [ ! -x "$FOLDX" ]; then
    echo "ERROR: foldx binary not found at $FOLDX"
    exit 1
fi

cd "$PROJ"

rm -rf "$RESULTS"/* 2>/dev/null || true
rm -f x.pdb x_Repair.pdb x_Repair.fxout 2>/dev/null || true

echo -e "filename\tn.cys" > filelist.txt

shopt -s nullglob
pdbs=("$INPUT"/*.pdb)
total=${#pdbs[@]}
current=0

for pdb in "${pdbs[@]}"; do
    base=$(basename "$pdb")
    current=$((current + 1))

    cp "$pdb" x.pdb

    awk '$4=="CYS"{print $5,$6}' "$pdb" | uniq > mutant_list.txt
    n_cys=$(wc -l < mutant_list.txt)

    if [ "$n_cys" -eq 0 ]; then
        echo -e "$base\t0" >> filelist.txt
        continue
    fi

    awk '{ printf "%sC%s%sA", sep, $1, $2; sep="," } END { print ";" }' mutant_list.txt > individual_list.txt

    echo "[STEP] RepairPDB [${current}/${total}] $base ($n_cys Cys)"
    "$FOLDX" --command=RepairPDB --pdb=x.pdb > /dev/null 2>&1
    echo "[OK] RepairPDB done [${current}/${total}]"

    echo "[STEP] BuildModel [${current}/${total}] $base ($n_cys Cys)"
    "$FOLDX" --command=BuildModel \
        --pdb=x_Repair.pdb \
        --mutant-file=individual_list.txt \
        --output-dir="$RESULTS" > /dev/null 2>&1
    echo "[OK] BuildModel done [${current}/${total}]"

    echo -e "$base\t$n_cys" >> filelist.txt
done

if [ -f "$RESULTS/Average_x_Repair.fxout" ]; then
    sed -i '1,8d' "$RESULTS/Average_x_Repair.fxout"
    paste -d "\t" filelist.txt "$RESULTS/Average_x_Repair.fxout" | \
        awk 'BEGIN{OFS="\t"}
             $2+0==$2 {print $0,-$5/23.06/$2; next}
             {print $0,"E (V)"}' \
        > "$RESULTS/final_result.txt"
    echo "[DONE] Pipeline complete"
else
    echo "ERROR: No output generated by FoldX"
    exit 1
fi
